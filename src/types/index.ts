export interface Deal {
  id: string;
  user_id: string;
  pipeline_id: string;
  stage_id: string;
  /**
   * Nullable after migration 004 — becomes NULL when the referenced
   * contact is deleted (ON DELETE SET NULL). History preserved.
   */
  contact_id: string | null;
  conversation_id?: string;
  assigned_to?: string;
  title: string;
  value: number;
  currency?: string;
  notes?: string;
  expected_close_date?: string;
  status?: DealStatus;
  created_at: string;
  updated_at?: string;
  contact?: Contact;
  stage?: PipelineStage;
  /** Hydrated by queries that embed `pipeline:pipelines(...)` — the inbox
   *  sidebar shows it so a contact's deals in different pipelines are
   *  told apart at a glance. Absent otherwise. */
  pipeline?: Pick<Pipeline, 'id' | 'name'>;
  assignee?: Profile;
}

